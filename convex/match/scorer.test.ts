// @vitest-environment node
// Scorer unit tests + the shared fixture that the Python agent's pytest also runs.
// UPDATE_FIXTURES=1 npx vitest run convex/match/scorer.test.ts rewrites the fixture.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { DEMO_JOBS } from "../../shared/fixtures/demo-jobs";
import type { CandidateJob, MatchSnapshot } from "../../shared/types";
import { coverageLine, scoreJob } from "./scorer";

const FIXTURE = resolve(process.cwd(), "shared/fixtures/scorer-cases.json");

const personas: Record<string, MatchSnapshot> = {
  sam: { skills: ["TypeScript", "React", "node", "PostgreSQL", "REST APIs", "GraphQL", "Python", "Docker", "Git", "Jest"], roleIds: ["full_stack_developer"], requiredAccommodations: ["remote_work", "flexible_hours"], locationText: "", remotePreference: "remote", profileVersion: 1 },
  p2: { skills: ["Python", "PyTorch", "NLP", "SQL", "pandas"], roleIds: ["ml_engineer"], requiredAccommodations: ["assistive_software"], locationText: "Austin", remotePreference: "either", profileVersion: 1 },
  p3: { skills: ["JS", "React", "CSS"], roleIds: ["full_stack_developer", "ml_engineer"], requiredAccommodations: ["written_alternatives", "remote_work"], locationText: "Chicago", remotePreference: "either", profileVersion: 1 },
};

const candidates: CandidateJob[] = DEMO_JOBS.map((j) => ({
  jobId: j.key,
  roleFamily: j.roleFamily,
  skills: j.skills,
  location: j.location,
  workplaceType: j.workplaceType,
  accommodations: j.accommodations,
}));

function buildCases() {
  const cases = [];
  for (const [name, snapshot] of Object.entries(personas))
    for (const job of candidates) {
      const r = scoreJob(snapshot, job);
      cases.push({ name: `${name}:${job.jobId}`, snapshot, job, expected: r && { score: r.score, factors: r.factors, accommodationCoverage: r.accommodationCoverage } });
    }
  return { _comment: "Generated by convex/match/scorer.test.ts. Run by agent/tests/test_scorer.py.", cases };
}

describe("scorer", () => {
  it("matches the shared fixture (regenerate with UPDATE_FIXTURES=1)", () => {
    const built = buildCases();
    if (process.env.UPDATE_FIXTURES) writeFileSync(FIXTURE, JSON.stringify(built, null, 1) + "\n");
    const stored = JSON.parse(readFileSync(FIXTURE, "utf8"));
    expect(stored.cases).toEqual(JSON.parse(JSON.stringify(built.cases)));
  });

  it("hides jobs outside chosen or adjacent role families", () => {
    const ml = candidates.find((c) => c.jobId === "quillmark-ml")!;
    expect(scoreJob(personas.sam, ml)).toBeNull();
  });

  it("applies the formula and alias normalization", () => {
    const r = scoreJob(personas.sam, candidates.find((c) => c.jobId === "lumen-fullstack")!)!;
    // 8 required matched of 8 required + 1 preferred (0.5): S = 8/8.5; R = 1; L = 1
    expect(r.score).toBe(Math.round(100 * (0.6 * (8 / 8.5) + 0.3 + 0.1)));
    expect(r.factors.skills.matched).toContain("Node.js");
    expect(r.factors.skills.missing).toEqual(["Kubernetes"]);
  });

  it("subtracts 25 for an explicit, quoted conflict with a required accommodation (A9)", () => {
    const job = candidates.find((c) => c.jobId === "corvid-backend")!;
    const withReq = scoreJob(personas.sam, job)!;
    const without = scoreJob({ ...personas.sam, requiredAccommodations: [] }, job)!;
    expect(without.score - withReq.score).toBe(25);
    expect(withReq.factors.conflicts[0].quote).toBe("This position is on-site five days a week at our Austin facility.");
  });

  it("caps S at 0.5 when a listing names no skills", () => {
    const r = scoreJob(personas.sam, candidates.find((c) => c.jobId === "harbor-junior")!)!;
    expect(r.factors.skills.limitedInfo).toBe(true);
    expect(r.factors.skills.ratio).toBe(0.5);
  });

  it("never lets preferred accommodations or missing info lower the score", () => {
    const job = candidates.find((c) => c.jobId === "fernway-frontend")!;
    const a = scoreJob(personas.sam, job)!;
    const b = scoreJob({ ...personas.sam, requiredAccommodations: [] }, job)!;
    expect(a.score).toBe(b.score);
    expect(coverageLine(a.accommodationCoverage)).toBe("Stated: 0 of 2. Not mentioned: 2.");
  });
});
